package Selecto::Domain::SourceRelationships;

use 5.034;
use strict;
use warnings;
no overloading;
use B ();
use bytes ();
use Encode qw(encode_utf8);
use JSON::PP ();
use Scalar::Util qw(reftype);
use Selecto::Domain::QueryContract ();
use Selecto::Error ();
use Selecto::Limits ();

my $LIMITS = Selecto::Limits->new;
my %FIELD_OP = map { $_ => 1 } qw(eq neq not_eq gt gte lt lte like case_insensitive_like
    contains starts_with ends_with between in not_in text_search match_against
    array_contains array_contained array_overlap array_eq);

sub _fail { Selecto::Error->throw('invalid_source_relationships', $_[0]); }
sub _string {
    return defined($_[0]) && !defined(reftype($_[0]))
        && (B::svref_2object(\$_[0])->FLAGS & B::SVf_POK());
}
sub _path {
    return 0 unless _string($_[0]);
    my $path = $_[0];
    $path =~ s/\A\s+|\s+\z//g;
    return length($path) && $path !~ /\A\.|\.\z|\.\./;
}
sub _type {
    return 'null' unless defined $_[0];
    return 'object' if ref($_[0]) eq 'HASH';
    return 'array' if ref($_[0]) eq 'ARRAY';
    return 'boolean' if ref($_[0]) eq 'JSON::PP::Boolean';
    return _string($_[0]) ? 'string' : 'number';
}
sub _bytes {
    my ($state, $value) = @_;
    $state->{bytes} += bytes::length(utf8::is_utf8($value) ? encode_utf8($value) : $value);
    _fail('source relationships exceed the generated metadata byte limit')
        if $state->{bytes} > $LIMITS->get('max_state_bytes');
}
sub _charge {
    my ($state, $value, $depth) = @_;
    $depth //= 0;
    _fail('source relationships exceed the generated metadata node or depth limit')
        if ++$state->{nodes} > $LIMITS->get('max_expression_nodes')
            || $depth > $LIMITS->get('max_expression_depth');
    if (ref($value) eq 'HASH') {
        for my $key (keys %$value) { _bytes($state, $key); _charge($state, $value->{$key}, $depth + 1); }
    } elsif (ref($value) eq 'ARRAY') {
        _charge($state, $_, $depth + 1) for @$value;
    } elsif (!ref($value)) {
        _bytes($state, defined($value) ? $value : '');
    }
}
sub _work {
    my ($state) = @_;
    _fail('source relationships exceed the field resolution work limit')
        if ++$state->{work} > $LIMITS->get('max_expression_nodes');
}
sub _error {
    my ($state, $code, $path, %attrs) = @_;
    my $error = {code => $code, path => $path, %attrs};
    _charge($state->{output}, $error);
    push @{$state->{errors}}, $error;
}
sub _object {
    my ($state, $value, $path) = @_;
    return $value if ref($value) eq 'HASH';
    _error($state, 'invalid_section_shape', $path, expected => 'object', actual => _type($value));
    return {};
}
sub _key {
    my ($state, $prefix, $id) = @_;
    _work($state);
    # Charge both parts before concatenation. Repeated long aliases cannot
    # amplify a compact admitted declaration beyond the generated byte budget.
    _bytes($state->{output}, $prefix);
    _bytes($state->{output}, $id);
    return $prefix . $id;
}
sub _relation {
    my ($state, $relation, $prefix) = @_;
    return unless ref($relation) eq 'HASH';
    my $columns = ref($relation->{columns}) eq 'HASH' ? $relation->{columns} : {};
    my $fields = ref($relation->{fields}) eq 'ARRAY' ? $relation->{fields} : [];
    for my $id (@$fields, sort keys %$columns) {
        _work($state);
        next unless _string($id);
        $state->{fields}{_key($state, $prefix, $id)} = 1;
    }
}
sub _joins {
    my ($state, $relation, $schemas, $joins, $prefix) = @_;
    return unless ref($relation) eq 'HASH' && ref($joins) eq 'HASH';
    my $associations = ref($relation->{associations}) eq 'HASH' ? $relation->{associations} : {};
    for my $id (sort keys %$joins) {
        _work($state);
        my $join = $joins->{$id};
        my $association = $associations->{$id};
        next unless ref($join) eq 'HASH' && ref($association) eq 'HASH'
            && _string($association->{queryable}) && ref($schemas->{$association->{queryable}}) eq 'HASH';
        my $target = $schemas->{$association->{queryable}};
        my $alias = _key($state, $prefix, $id);
        my $child_prefix = _key($state, $alias, '.');
        _relation($state, $target, $child_prefix);
        if (_string($join->{type}) && $join->{type} eq 'star_dimension' && _path($join->{display_field})) {
            $state->{fields}{_key($state, $alias, '_display')} = 1;
        }
        _joins($state, $target, $schemas, $join->{joins}, $child_prefix);
    }
}
sub _known_field {
    my ($state, $id, $value, $path, $part) = @_;
    return unless defined $value;
    if (!_string($value)) {
        _error($state, "invalid_source_relationship_$part", $path,
            source_relationship => $id, actual => _type($value));
    } elsif (!exists $state->{fields}{$value}) {
        _error($state, "source_relationship_${part}_not_found", $path,
            source_relationship => $id, $part => $value);
    }
}
sub _static_path {
    my ($state, $id, $value, $path, $code) = @_;
    return unless defined $value;
    _error($state, $code, $path, source_relationship => $id, actual => _type($value)) unless _path($value);
}
sub _required {
    my ($state, $id, $spec, $path, $code, @keys) = @_;
    my @missing = grep { !exists $spec->{$_} } @keys;
    _error($state, $code, $path, source_relationship => $id, keys => \@missing) if @missing;
}
sub _filter_error {
    my ($state, $id, $kind, $path, $value) = @_;
    _error($state, "invalid_source_relationship_filter_$kind", $path,
        source_relationship => $id, actual => _type($value));
}
sub _filter {
    my ($state, $id, $filter, $path) = @_;
    _work($state);
    unless (ref($filter) eq 'ARRAY' && @$filter) {
        _filter_error($state, $id, 'expression', $path, $filter); return;
    }
    my $op = $filter->[0];
    my $operator = _string($op) && $op =~ /\S/;
    my $field = $operator && $FIELD_OP{$op};
    my $logical = $operator && ($op eq 'and' || $op eq 'or');
    my $unary = $operator && $op eq 'not';
    if (@$filter == 2 && $logical) {
        unless (ref($filter->[1]) eq 'ARRAY') {
            _filter_error($state, $id, 'operands', $path, $filter->[1]); return;
        }
        _filter($state, $id, $filter->[1][$_], [@$path, $_]) for 0 .. $#{$filter->[1]};
    } elsif (@$filter == 2 && $unary) {
        _filter($state, $id, $filter->[1], [@$path, 'operand']);
    } elsif ((@$filter == 3 || @$filter == 4) && $field) {
        _filter_error($state, $id, 'path', [@$path, 'field'], $filter->[1]) unless _path($filter->[1]);
    } else {
        _filter_error($state, $id, ($field || $logical || $unary) ? 'operands'
            : $operator ? 'operator' : 'expression', $path, $filter);
    }
}
sub _relationship {
    my ($state, $id, $spec) = @_;
    my $path = ['source_relationships', $id];
    unless (ref($spec) eq 'HASH') {
        _error($state, 'invalid_section_shape', $path, source_relationship => $id,
            expected => 'object', actual => _type($spec)); return;
    }
    _required($state, $id, $spec, $path, 'source_relationship_missing_required_keys', qw(target_domain source_field target_field));
    for my $key (qw(target_domain target_field)) {
        _error($state, "invalid_source_relationship_$key", [@$path, $key],
            source_relationship => $id, actual => _type($spec->{$key}))
            if defined($spec->{$key}) && !_string($spec->{$key});
    }
    _known_field($state, $id, $spec->{source_field}, [@$path, 'source_field'], 'source_field');
    _static_path($state, $id, $spec->{source_path}, [@$path, 'source_path'], 'invalid_source_relationship_source_path');
    if (defined $spec->{capability}) {
        if (!_string($spec->{capability})) {
            _error($state, 'invalid_source_relationship_capability', [@$path, 'capability'], source_relationship => $id);
        } elsif (!exists $state->{capabilities}{$spec->{capability}}) {
            _error($state, 'source_relationship_capability_not_found', [@$path, 'capability'],
                source_relationship => $id, capability => $spec->{capability});
        }
    }
    if (defined $spec->{virtual_join}) {
        if (ref($spec->{virtual_join}) ne 'ARRAY') {
            _error($state, 'invalid_source_relationship_virtual_join', [@$path, 'virtual_join'], source_relationship => $id);
        } else {
            for my $i (0 .. $#{$spec->{virtual_join}}) {
                _work($state);
                my $entry = $spec->{virtual_join}[$i];
                my $entry_path = [@$path, 'virtual_join', $i];
                if (ref($entry) ne 'HASH') {
                    _error($state, 'invalid_source_relationship_virtual_join_entry', $entry_path, source_relationship => $id); next;
                }
                _required($state, $id, $entry, $entry_path, 'source_relationship_virtual_join_missing_required_keys', qw(working_field source_field));
                _known_field($state, $id, $entry->{working_field}, [@$entry_path, 'working_field'], 'virtual_join_working_field');
                _static_path($state, $id, $entry->{source_field}, [@$entry_path, 'source_field'], 'invalid_source_relationship_virtual_join_source_field');
                _error($state, 'invalid_source_relationship_virtual_join_required', [@$entry_path, 'required'], source_relationship => $id)
                    if defined($entry->{required}) && ref($entry->{required}) ne 'JSON::PP::Boolean';
            }
        }
    }
    if (defined $spec->{filters}) {
        if (ref($spec->{filters}) ne 'ARRAY') {
            _error($state, 'invalid_source_relationship_filters', [@$path, 'filters'], source_relationship => $id);
        } else {
            _filter($state, $id, $spec->{filters}[$_], [@$path, 'filters', $_]) for 0 .. $#{$spec->{filters}};
        }
    }
}
sub _state {
    my ($given) = @_;
    # Admission covers the complete input, including unrelated extension keys,
    # before field indexing, diagnostics or projection can inspect any values.
    my $contract = Selecto::Domain::QueryContract->copy_declaration($given);
    my $state = {contract => $contract, fields => {}, errors => [], work => 0,
        output => {nodes => 0, bytes => 0}};
    my $source = _object($state, $contract->{source} // {}, ['source']);
    my $schemas = _object($state, $contract->{schemas} // {}, ['schemas']);
    _relation($state, $source, '');
    for my $id (sort keys %$schemas) { _relation($state, $schemas->{$id}, _key($state, $id, '.')); }
    my $custom = _object($state, $contract->{custom_columns} // {}, ['custom_columns']);
    $state->{fields}{_key($state, '', $_)} = 1 for sort keys %$custom;
    _joins($state, $source, $schemas, _object($state, $contract->{joins} // {}, ['joins']), '');
    $state->{capabilities} = _object($state, $contract->{capabilities} // {}, ['capabilities']);
    my $relationships = exists($contract->{source_relationships}) ? $contract->{source_relationships} : {};
    $state->{relationships} = _object($state, $relationships, ['source_relationships']);
    for my $id (sort keys %{$state->{relationships}}) { _work($state); _relationship($state, $id, $state->{relationships}{$id}); }
    return $state;
}
sub validate {
    my ($class, $given) = @_;
    my $state = _state($given);
    my $valid = @{$state->{errors}} ? 0 : 1;
    return Selecto::Domain::QueryContract->copy_declaration({
        valid => bless(\$valid, 'JSON::PP::Boolean'), errors => $state->{errors}, warnings => []});
}
sub project {
    my ($class, $given) = @_;
    my $state = _state($given);
    Selecto::Error->throw('invalid_source_relationships', 'source relationship declarations failed validation',
        {errors => $state->{errors}, warnings => []}) if @{$state->{errors}};
    my @relationships;
    for my $id (sort keys %{$state->{relationships}}) {
        my $spec = $state->{relationships}{$id};
        my $descriptor = {id => $id,
            (map { $_ => $spec->{$_} } qw(target_domain source_field target_field source_path)),
            filters_count => ref($spec->{filters}) eq 'ARRAY' ? scalar(@{$spec->{filters}}) : 0,
            virtual_join_count => ref($spec->{virtual_join}) eq 'ARRAY' ? scalar(@{$spec->{virtual_join}}) : 0};
        _charge($state->{output}, $descriptor);
        push @relationships, $descriptor;
    }
    return Selecto::Domain::QueryContract->copy_declaration({source_relationships => \@relationships})->{source_relationships};
}

1;

__END__

=head1 NAME

Selecto::Domain::SourceRelationships - declared cross-domain relationship metadata

=head1 METHODS

C<validate($plain_domain)> returns C<valid>, structured C<errors>, and C<warnings>.
C<project($plain_domain)> validates and returns sorted canonical descriptors with
the declared target domain, local and target fields, source path, filter count
and virtual-join count. Both methods accept complete bounded portable domain
declarations, with no callbacks, tied containers, cycles or arbitrary objects.

Local fields resolve from source, schema, custom columns and actual declared
association joins. Static dotted paths, nested logical filters and virtual-join
metadata are validated without SQL, target-domain lookup, context resolution or
authorization. A relationship capability, when supplied, must name a declared
capability; this metadata validation does not grant it. Optional null metadata follows the portable domain contract.
The existing raw consumer projection and native parser remain separate APIs.

=cut
