package Selecto::Domain::Projection;

use 5.034;
use strict;
use warnings;
no overloading;
use bytes ();
use Encode qw(encode_utf8);
use JSON::PP ();
use Scalar::Util qw(blessed);
use Selecto::Domain::QueryContract ();
use Selecto::Error ();
use Selecto::Limits ();

my $LIMITS = Selecto::Limits->new;
my %PROJECTION = map { $_ => 1 } qw(query write ui api query_contract);
my @QUERY = qw(default_selected required_selected required_filters required_order_by required_group_by filters functions query_members query_library published_views);
my @QUERY_EXTRA = qw(custom_columns json_schemas subfilters window_functions pagination retarget);
my @UI_QUERY = qw(default_selected required_selected required_filters required_order_by required_group_by filters);
my @UI_EXTRA = qw(columns custom_columns json_schemas pagination redact_fields);
my @WRITE = qw(columns writes rules actions events capabilities source_relationships choice_sources co_domains);
my @UI = qw(detail_actions editors components rules actions capabilities choice_sources co_domains);
my @API = qw(writes rules actions events capabilities source_relationships choice_sources co_domains detail_actions editors);
my %OBJECT = map { $_ => 1 } qw(source schemas joins domain_data columns custom_columns json_schemas subfilters window_functions pagination retarget filters functions query_members query_library published_views writes rules actions events capabilities source_relationships choice_sources co_domains detail_actions editors components);
my %LIST = map { $_ => 1 } qw(extensions default_selected required_selected required_filters required_order_by required_group_by redact_fields);
my %NUMERIC = map { $_ => 1 } qw(integer float decimal);
my %TEMPORAL = map { $_ => 1 } qw(date time datetime naive_datetime naive_datetime_usec utc_datetime utc_datetime_usec);
my %TEXT = map { $_ => 1 } qw(string text);
my %EXACT = map { $_ => 1 } qw(boolean uuid enum);

sub _fail {
    my ($message, $reason, $path) = @_;
    Selecto::Error->throw('invalid_domain_projection', $message,
        {reason => $reason // 'invalid_declaration', path => $path // []});
}
sub _name { defined($_[0]) && !ref($_[0]) && $_[0] =~ /\S/ }
sub _object {
    my ($value, $path) = @_;
    _fail('domain projection section must be an object', 'invalid_declaration', $path)
        unless ref($value) eq 'HASH';
    return $value;
}
sub _bytes {
    my ($budget, $value) = @_;
    $budget->{bytes} += bytes::length(utf8::is_utf8($value) ? encode_utf8($value) : $value);
    _fail('domain projection exceeds its generated byte limit', 'resource_limit')
        if $budget->{bytes} > $LIMITS->get('max_state_bytes');
}
sub _charge {
    my ($budget, $value, $depth) = @_;
    _fail('domain projection exceeds its generated node/depth limit', 'resource_limit')
        if ++$budget->{nodes} > $LIMITS->get('max_expression_nodes')
            || ($depth // 0) > $LIMITS->get('max_expression_depth');
    if (!ref($value)) { _bytes($budget, defined($value) ? $value : ''); return; }
    return if blessed($value); # Only admitted canonical JSON booleans remain.
    if (ref($value) eq 'ARRAY') { _charge($budget, $_, ($depth // 0) + 1) for @$value; return; }
    for my $key (keys %$value) {
        _bytes($budget, $key);
        _charge($budget, $value->{$key}, ($depth // 0) + 1);
    }
}
sub _key {
    my ($budget, @parts) = @_;
    _bytes($budget, $_) for @parts; # Admit before allocating a repeated prefix.
    return join('', @parts);
}
sub _bool {
    my ($column, $names, $default) = @_;
    for my $key (@$names) {
        next unless exists $column->{$key};
        my $value = $column->{$key};
        return $$value ? 1 : 0 if blessed($value); # Shared admission canonicalized booleans.
        _fail('field surface flags must be boolean', 'invalid_declaration', [$key])
            unless defined($value) && !ref($value) && "$value" =~ /\A[01]\z/;
        return $value ? 1 : 0;
    }
    return $default;
}
sub _json_bool { my $value = $_[0] ? 1 : 0; return bless \$value, 'JSON::PP::Boolean'; }
sub _comparators {
    my ($type) = @_;
    return [qw(eq neq gt gte lt lte between in not_in is_null not_null)] if $NUMERIC{$type} || $TEMPORAL{$type};
    return [qw(eq neq contains starts_with ends_with in not_in is_null not_null)] if $TEXT{$type};
    return [qw(eq neq is_null not_null)] if $type eq 'boolean';
    return [qw(eq neq in not_in is_null not_null)];
}
sub _override_list {
    my ($column, @keys) = @_;
    for my $key (@keys) {
        next unless exists $column->{$key};
        _fail('field surface lists must be arrays', 'invalid_declaration', [$key]) unless ref($column->{$key}) eq 'ARRAY';
        return $column->{$key};
    }
    return;
}
sub _field {
    my ($state, $parts, $field, $column, $relation, $kind) = @_;
    _object($column, ['columns', $field]);
    my $id = _key($state->{budget}, @$parts);
    return if exists $state->{fields}{$id}; # Reference precedence: source, schema, custom, join.
    my $type = defined($column->{type}) && !ref($column->{type}) ? lc($column->{type}) : '';
    my $internal = _bool($column, ['internal'], 0);
    my $detail = !$internal && _bool($column, [qw(detail_selectable detail_selectable? selectable selectable?)], 1);
    my $filterable = _bool($column, [qw(filterable filterable? query_filterable query_filterable?)],
        $state->{filter_fields}{$id} || (($kind eq 'source' || $kind eq 'schema') && !$internal) ? 1 : 0);
    my $sortable = _bool($column, [qw(sortable sortable?)], $detail && ($NUMERIC{$type} || $TEMPORAL{$type} || $TEXT{$type} || $EXACT{$type}));
    my $groupable = _bool($column, [qw(groupable groupable?)], $detail && ($NUMERIC{$type} || $TEMPORAL{$type} || $type eq 'string' || $EXACT{$type}));
    my $aggregatable = _bool($column, [qw(aggregatable aggregatable?)], $detail && $NUMERIC{$type});
    my $comparators = _override_list($column, qw(comparators operators));
    my $aggregates = _override_list($column, qw(aggregate_functions aggregates));
    my $descriptor = {id => $id, source => $kind, relation => $relation, field => $field,
        type => $column->{type}, label => $column->{name}, capability => $column->{capability},
        capability_target => $column->{capability_target}, choice_source => $column->{choice_source},
        detail_selectable => _json_bool($detail), filterable => _json_bool($filterable),
        sortable => _json_bool($sortable), groupable => _json_bool($groupable), aggregatable => _json_bool($aggregatable),
        comparators => $comparators // ($filterable ? _comparators($type) : []),
        aggregate_functions => $aggregates // ($aggregatable ? [qw(count count_distinct sum avg min max)] : []),
        map { $_ => $column->{$_} } qw(unit behavior default_grouping default_aggregate)};
    _charge($state->{budget}, $descriptor, 0);
    $state->{fields}{$id} = $descriptor;
}
sub _relation {
    my ($state, $relation, $prefix, $relation_id, $kind) = @_;
    _object($relation, ['relation', $relation_id]);
    my $columns = _object($relation->{columns} // {}, ['relation', $relation_id, 'columns']);
    my $fields = exists($relation->{fields}) ? $relation->{fields} : [sort keys %$columns];
    _fail('relation fields must be an array', 'invalid_declaration', ['relation', $relation_id, 'fields']) unless ref($fields) eq 'ARRAY';
    for my $field (@$fields) {
        _fail('relation field is absent from declared columns', 'invalid_declaration', ['relation', $relation_id, 'fields'])
            unless _name($field) && exists $columns->{$field};
        _field($state, [$prefix, $field], $field, $columns->{$field}, $relation_id, $kind);
    }
}
sub _joins {
    my ($state, $relation, $joins, $prefix, $parent, $depth, $components) = @_;
    _fail('join metadata exceeds its depth/work limit', 'resource_limit')
        if $depth > $LIMITS->get('max_expression_depth') || ++$state->{work} > $LIMITS->get('max_expression_nodes');
    my $associations = _object($relation->{associations} // {}, ['associations']);
    for my $id (sort keys %{_object($joins, ['joins'])}) {
        my $join = _object($joins->{$id}, ['joins', $id]);
        my $association = _object($associations->{$id}, ['associations', $id]);
        my $target_id = $association->{queryable};
        _fail('join metadata has no declared target schema', 'invalid_declaration', ['joins', $id])
            unless _name($target_id) && ref($state->{schemas}{$target_id}) eq 'HASH';
        my $target = $state->{schemas}{$target_id};
        my $path = _key($state->{budget}, $prefix, $id, '.');
        _relation($state, $target, $path, $path =~ s/\.$//r, 'join');
        my $nested = _object($join->{joins} // {}, ['joins', $id, 'joins']);
        # Declared ids are path components. Splitting a rendered id would both
        # lose that boundary and amplify a long dotted scalar into an array.
        my $entry = {id => $id, path => [@$components, $id], parent => $parent,
            target_schema => $target_id, type => $join->{type},
            fields => $target->{fields} // [sort keys %{_object($target->{columns} // {}, ['columns'])}], nested_count => scalar(keys %$nested)};
        _charge($state->{budget}, $entry, 0);
        push @{$state->{joins}}, $entry;
        _joins($state, $target, $nested, $path, $target_id, $depth + 1, $entry->{path}) if keys %$nested;
    }
}
sub _query_contract {
    my ($contract) = @_;
    my $metadata = Selecto::Domain::QueryContract->project($contract);
    my $source = _object($contract->{source} // {}, ['source']);
    my $schemas = _object($contract->{schemas} // {}, ['schemas']);
    my $state = {fields => {}, joins => [], schemas => $schemas, filter_fields => {}, work => 0,
        budget => {nodes => 0, bytes => 0}};
    for my $filter (@{$metadata->{filters}}) {
        $state->{filter_fields}{$filter->{field}} = 1 if defined($filter->{field}) && !ref($filter->{field});
    }
    _relation($state, $source, '', 'source', 'source');
    for my $id (sort keys %$schemas) { _relation($state, $schemas->{$id}, _key($state->{budget}, $id, '.'), $id, 'schema'); }
    my $custom = _object($contract->{custom_columns} // {}, ['custom_columns']);
    for my $id (sort keys %$custom) { _field($state, [$id], $id, $custom->{$id}, undef, 'custom_column'); }
    _joins($state, $source, $contract->{joins} // {}, '', 'source', 0, []);
    my $result = {schema_version => $contract->{schema_version} // 1, name => $contract->{name}, projection => 'query_contract',
        source => {map { $_ => $source->{$_} } qw(source_table primary_key)},
        fields => [map { $state->{fields}{$_} } sort keys %{$state->{fields}}], joins => $state->{joins},
        defaults => $metadata->{defaults}, filters => $metadata->{filters}, functions => $metadata->{functions},
        query_members => $contract->{query_members} // {}, query_library => $contract->{query_library} // {},
        published_views => $contract->{published_views} // {}, source_relationships => $contract->{source_relationships} // {},
        choice_sources => $contract->{choice_sources} // {}, co_domains => $contract->{co_domains} // {},
        capability_ids => [sort keys %{$contract->{capabilities} // {}}]};
    $result->{source}{tenant_field} = $source->{tenant_field} if defined $source->{tenant_field};
    $result->{$_} = $contract->{$_} for grep { defined $contract->{$_} } qw(domain_version domain_fingerprint);
    return $result;
}
sub _take {
    my ($result, $contract, @keys) = @_;
    $result->{$_} = $contract->{$_} for grep { exists $contract->{$_} } @keys;
}
sub project {
    my ($class, $given, $projection) = @_;
    my $contract = Selecto::Domain::QueryContract->copy_declaration($given);
    _fail('unknown domain projection', 'unknown_projection') unless _name($projection) && $PROJECTION{$projection};
    for my $key (keys %$contract) {
        _fail('domain projection section has an invalid shape', 'invalid_declaration', [$key])
            if defined($contract->{$key}) && (($OBJECT{$key} && ref($contract->{$key}) ne 'HASH')
                || ($LIST{$key} && ref($contract->{$key}) ne 'ARRAY'));
    }
    if ($projection eq 'query_contract') {
        return Selecto::Domain::QueryContract->copy_declaration(_query_contract($contract));
    }
    my $result = {schema_version => $contract->{schema_version} // 1, name => $contract->{name}, source => $contract->{source},
        schemas => $contract->{schemas} // {}, joins => $contract->{joins} // {}, domain_data => $contract->{domain_data} // {}, extensions => $contract->{extensions} // []};
    $result->{$_} = $contract->{$_} for grep { defined $contract->{$_} } qw(domain_version domain_fingerprint);
    if ($projection eq 'query') { _take($result, $contract, @QUERY, @QUERY_EXTRA); }
    elsif ($projection eq 'write') { $result->{$_} = $contract->{$_} // {} for @WRITE; }
    elsif ($projection eq 'ui') {
        _take($result, $contract, @UI_QUERY, @UI_EXTRA);
        $result->{$_} = $contract->{$_} // {} for @UI;
    } else {
        _take($result, $contract, @QUERY, @QUERY_EXTRA, qw(columns redact_fields));
        $result->{$_} = $contract->{$_} // {} for @API;
    }
    return Selecto::Domain::QueryContract->copy_declaration($result);
}

1;

