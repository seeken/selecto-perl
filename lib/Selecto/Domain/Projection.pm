=head1 NAME

Selecto::Domain::Projection - bounded plain consumer domain projections

=head1 METHODS

C<project($plain_contract, $consumer)> supports C<query>, C<write>, C<ui>,
C<api>, and C<query_contract>. Consumer maps use explicit section allowlists;
query-contract fields derive from declared source/schema/custom/join columns.
Top-level UI column overrides do not rewrite source field metadata. Redaction
declarations are exposed only by UI/API maps. Unknown projection names throw
C<invalid_domain_projection> with C<reason = unknown_projection>.

The complete input is admitted as bounded plain callback-free metadata before
copying. Generated field names and descriptors are budgeted before storage;
returned data is isolated from input. This API does not configure native queries,
execute callbacks or grant field access. Existing raw query_contract/Identity
APIs retain their separate behavior. Import projections are not implemented.

=cut
